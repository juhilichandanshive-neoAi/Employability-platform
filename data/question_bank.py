EXPANDED_QUESTION_BANK = {
    "cloud": {
        "easy": CLOUD_EASY,
        "moderate": CLOUD_MODERATE,
        "hard": CLOUD_HARD,
    },
    "cyber": {
        "easy": CYBER_EASY,
        "moderate": CYBER_MODERATE,
        "hard": CYBER_HARD,
    },
}


def get_questions_for_domain(domain: str, difficulty: str | None = None) -> list[dict]:
    """Return all questions for a domain, optionally filtered by difficulty."""
    domain_bank = EXPANDED_QUESTION_BANK.get(domain, {})
    if difficulty and difficulty in domain_bank:
        return list(domain_bank[difficulty])
    # Return all difficulties combined
    all_questions = []
    for diff_questions in domain_bank.values():
        all_questions.extend(diff_questions)
    return all_questions


def get_all_question_ids(domain: str, difficulty: str | None = None) -> set[str]:
    """Return all question IDs for a domain/difficulty combination."""
    return {q["id"] for q in get_questions_for_domain(domain, difficulty)}
